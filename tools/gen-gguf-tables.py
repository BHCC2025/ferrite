#!/usr/bin/env python3
"""Generate kernels/k-gguf/src/tables.rs (the IQ codebooks) from ggml-common.h. Shared by the kernel crate and the
host crates (include!). Usage: gen-gguf-tables.py <ggml-common.h> <out.rs>"""
import re, sys
src = open(sys.argv[1]).read()
want = [("ksigns_iq2xs", "u8"), ("iq2s_grid", "u64"), ("iq3xxs_grid", "u32"), ("iq3s_grid", "u32"), ("kvalues_iq4nl", "i8")]
out = ["// Generated by tools/gen-gguf-tables.py from ggml-common.h (llama.cpp, MIT). Do not edit.",
       "// The IQ codebooks: values only, shared by k-gguf (device) and fe-ggq (host) through include!.", ""]
for name, ty in want:
    m = re.search(r"GGML_TABLE_BEGIN\(\w+,\s*%s,\s*(\w+)\)(.*?)GGML_TABLE_END" % name, src, re.S)
    vals = re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(2))
    n = len(vals)
    out.append("#[allow(clippy::unreadable_literal)]")
    out.append(f"pub static {name.upper()}: [{ty}; {n}] = [")
    for i in range(0, n, 8):
        out.append("    " + ", ".join(vals[i:i+8]) + ",")
    out.append("];")
    out.append("")
open(sys.argv[2], "w").write("\n".join(out))
